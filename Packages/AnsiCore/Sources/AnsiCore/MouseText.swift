/// The Apple IIe enhanced and IIc MouseText characters (shown for inverse 0x40-0x5F while
/// MouseText is on): 32 small pictures drawn for AnsiView from their descriptions (apples, arrows,
/// hourglass, check marks, scroll bar and window frame pieces). No ROM data was copied.
enum MouseText {
    /// Rows of 8 pixels, `#` lit, rows separated by `/`.
    static let pictures: [String] = [
        "....#.../...#..../.##.##../########/#######./#######./.######./..#.#...", // 40 closed apple
        "....#.../...#..../.##.##../#......#/#......./#......#/.#....#./..#.#...", // 41 open apple
        "#......./##....../###...../####..../#####.../##.##.../#...##../.....##.", // 42 pointer
        "########/.#....#./..#..#../...##.../...##.../..#..#../.#....#./########", // 43 hourglass
        "......../.......#/......#./#....#../.#..#.../..##..../...#..../........", // 44 check mark
        "########/#######./######.#/.####.##/#.##.###/##..####/###.####/########", // 45 inverse check
        "...##.../...##.../.####.../#.##.#../..##..../.#..#.../#....#../........", // 46 running figure
        "...##.../...##.../..####../.#.##.#./...##.../..#..#../..#...#./........", // 47 standing figure
        "...#..../..#...../.#....../########/.#....../..#...../...#..../........", // 48 left arrow
        "......../......../......../......../......../......../#..#..#./........", // 49 ellipsis
        "...#..../...#..../...#..../...#..../#..#..#./.#.#.#../..###.../...#....", // 4A down arrow
        "...#..../..###.../.#.#.#../#..#..#./...#..../...#..../...#..../...#....", // 4B up arrow
        "########/......../......../......../......../......../......../........", // 4C top line
        ".......#/.......#/..#....#/.##....#/########/.##...../..#...../........", // 4D return
        "########/########/########/########/########/########/########/########", // 4E solid block
        "########/#......#/#..#...#/#.##...#/#..#...#/#......#/#......#/########", // 4F scroll left
        "########/#......#/#...#..#/#...##.#/#...#..#/#......#/#......#/########", // 50 scroll right
        "########/#......#/#......#/#.####.#/#..##..#/#......#/#......#/########", // 51 scroll down
        "########/#......#/#..##..#/#.####.#/#......#/#......#/#......#/########", // 52 scroll up
        "......../......../......../########/......../......../......../........", // 53 middle line
        "#......./#......./#......./#......./#......./#......./#......./########", // 54 lower left corner
        "....#.../.....#../......#./########/......#./.....#../....#.../........", // 55 right arrow
        "#.#.#.#./.#.#.#.#/#.#.#.#./.#.#.#.#/#.#.#.#./.#.#.#.#/#.#.#.#./.#.#.#.#", // 56 shade
        ".#.#.#.#/#.#.#.#./.#.#.#.#/#.#.#.#./.#.#.#.#/#.#.#.#./.#.#.#.#/#.#.#.#.", // 57 shade, other phase
        "......../.####.../#....###/#......./#......./#......./########/........", // 58 folder left
        "......../......../#######./.......#/.......#/.......#/########/........", // 59 folder right
        ".......#/.......#/.......#/.......#/.......#/.......#/.......#/.......#", // 5A right bar
        "...#..../..###.../.#####../#######./.#####../..###.../...#..../........", // 5B diamond
        "########/......../......../......../......../......../......../########", // 5C top and bottom
        "...#..../...#..../...#..../#######./...#..../...#..../...#..../........", // 5D plus
        "########/##...../##....../##....../##....../##....../##....../########", // 5E boxed left bar
        "#......./#......./#......./#......./#......./#......./#......./#.......", // 5F left bar
    ]

    /// The 32 glyphs, 8x8 each, row major.
    static func glyphs() -> [[Bool]] {
        pictures.map { picture in
            picture.split(separator: "/").flatMap { row in
                (Array(row) + Array(repeating: ".", count: 8)).prefix(8).map { $0 == "#" }
            }
        }
    }
}
